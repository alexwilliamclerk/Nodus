import {copyFile, mkdir} from 'node:fs/promises';
import {readFileSync} from 'node:fs';
const {version}=JSON.parse(readFileSync('package.json','utf8'));
const platform=process.argv[2];
if(!['mac','win','linux'].includes(platform))throw new Error('Expected mac, win, or linux');
const source=platform==='mac'?`dist/Nodus-${version}-arm64.dmg`:platform==='win'?`dist/Nodus-Setup-${version}-x64.exe`:`dist/Nodus-${version}-linux-x86_64.AppImage`;
const target=platform==='mac'?'Nodus-mac-arm64.dmg':platform==='win'?'Nodus-windows-x64.exe':'Nodus-linux-x64.AppImage';
await mkdir('release-assets',{recursive:true});
await copyFile(source,`release-assets/${target}`);
console.log(`Prepared ${target}`);
